"""Run stall detection, timetable slip, the bottleneck table and Experiment 6, and write the results.

Reads Member C's progress_trajectories.csv and planned_timetables.csv and the pseudonymised final
reports. Writes CSVs to data/processed (not committed) and a Markdown report.

    python -m app.progress.stall_report [--out docs/stall-detection.md]
"""
import argparse
import logging
import sys
from datetime import date
from pathlib import Path
from statistics import median

from app.progress import bottleneck, extension_predictor, stall_detector, timetable_slip
from app.statistics.confidence_intervals import rate
from config.config import ROOT, get_config
from app.ingestion.data_inventory import table
from app.logging_setup import configure_logging

logger = logging.getLogger(__name__)

STATUSES = ["on time", "early", "late", "overdue", "not due yet"]


def shown(path):
    try:
        return Path(path).resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return Path(path).as_posix()


def stage_name(stage):
    return stage.replace("_", " ").capitalize()


def lead_text(months):
    if not months:
        return "-"
    return f"{median(months):g} months (range {min(months)}-{max(months)})"


def build(trajectories, timetables, outcomes, cfg):
    episodes = stall_detector.detect(trajectories, cfg.STALL_TOLERANCE, cfg.STALL_MIN_REPORTS)
    slip = timetable_slip.compute(timetables, trajectories, cfg.REPORT_INTERVAL_MONTHS)
    experiment = []
    for rule in extension_predictor.rules(cfg.STALL_TOLERANCE, cfg.STALL_MIN_REPORTS):
        predictions = extension_predictor.predict(trajectories, timetables, outcomes, rule,
                                                  cfg.REPORT_INTERVAL_MONTHS)
        experiment.append((rule, predictions,
                           extension_predictor.summarise(predictions, cfg.REPORT_INTERVAL_MONTHS)))
    return episodes, slip, experiment


def render(trajectories, outcomes, episodes, slip, experiment, cfg, sources):
    funded = sorted(trajectories["grant_id"].unique())
    completed = sorted(g for g in outcomes if g in set(funded))
    running = sorted(set(funded) - set(outcomes))
    level = cfg.CONFIDENCE_LEVEL
    out = [
        "# stall detection, timetable slip and extension prediction",
        "",
        f"Generated by `python -m app.progress.stall_report` on {date.today()} from "
        + ", ".join(f"`{s}`" for s in sources) + ".",
        "Methods and thresholds are in `docs/statistics-methodology.md` and were fixed before this was run.",
        "Nothing here is a judgement about a researcher. A flagged grant means **review recommended**: a",
        "stage can stop for many reasons (ethics delay, equipment, illness) and a person has to ask.",
        "",
        "## settings",
        "",
        f"- A stage is stalled when it has started, is not finished, and gained {cfg.STALL_TOLERANCE:g} percentage "
        f"points or less since the previous report. Alert after {cfg.STALL_MIN_REPORTS} such report(s).",
        f"- Reports are every {cfg.REPORT_INTERVAL_MONTHS} months, so timetable slip is measured in quarters.",
        "",
        "## data",
        "",
        f"{len(trajectories)} progress reports from {len(funded)} funded grants. {len(completed)} grants are "
        f"completed (have a final report), {sum(outcomes[g] for g in completed)} of them extended. "
        f"{len(running)} are still running.",
        "",
        "## stalls",
        "",
        f"{len(episodes)} stall episodes in **{episodes['grant_id'].nunique() if not episodes.empty else 0} of "
        f"{len(funded)} funded grants**.",
        "",
        table(["Stage", "Episodes", "Grants", "Median length (reports)"],
              [[stage_name(s), len(e), e["grant_id"].nunique(), f"{e['reports'].median():g}"]
               for s, e in episodes.groupby("stage", sort=False)] if not episodes.empty else []),
        "",
        f"## portfolio bottleneck (n = {len(completed)} completed grants)",
        "",
        "Each grant is counted once, at the stage of its longest stall.",
        "",
    ]
    dist = bottleneck.distribution(episodes, completed)
    out += [
        table(["Stage", "Grants", "Share"],
              [[stage_name(r.stage) if r.stage != bottleneck.NO_STALL else "*No stall*", r.grants,
                f"{r.share:.0%}"] for r in dist.itertuples()]),
        "",
        f"## timetable slip ({slip['grant_id'].nunique()} grants, {len(slip)} tasks)",
        "",
        "Slip = quarter the stage reached 100% minus the quarter it was planned to end in. Overdue = not "
        "finished and already past its planned quarter at the latest report.",
        "",
    ]
    rows = []
    for stage, s in slip.groupby("stage", sort=False):
        counts = s["status"].value_counts()
        finished = s[s["done_quarter"].notna()]["slip_quarters"]
        rows.append([stage_name(stage), len(s)] + [int(counts.get(x, 0)) for x in STATUSES]
                    + [f"{finished.mean():.2f}" if len(finished) else "-"])
    out += [
        table(["Stage", "Tasks"] + [x.capitalize() for x in STATUSES] + ["Mean slip of finished (quarters)"], rows),
        "",
        f"## extension prediction (Experiment 6, n = {len(completed)} completed grants)",
        "",
        "Only reports up to each grant's planned end are used. Lead time = planned end minus the month of "
        "the first flag. \"Early\" = flagged at least one report before the planned end.",
        "",
    ]
    rows = []
    for rule, _, s in experiment:
        rows.append([rule["name"], rate(s["detected"], s["extended"], level),
                     rate(s["detected_early"], s["extended"], level),
                     rate(s["false_alarms"], s["on_time"], level), lead_text(s["lead_months"])])
    out += [
        table(["Rule", "Detection rate", "Detected early", "False positive rate", "Lead time (median)"], rows),
        "",
    ]
    main_rule, main_predictions, main = experiment[0]
    out += [
        f"<details><summary>Extended grants the main rule missed ({len(main['missed'])})</summary>",
        "",
        ", ".join(main["missed"]) or "none",
        "",
        "</details>",
        "",
        "## review recommended (running grants)",
        "",
    ]
    alerts = []
    for grant_id in running:
        ongoing = episodes[(episodes["grant_id"] == grant_id) & episodes["ongoing"]]
        late = slip[(slip["grant_id"] == grant_id) & (slip["status"] == "overdue")]
        reasons = [f"{stage_name(r.stage)} not moving since Q{r.start_quarter}" for r in ongoing.itertuples()]
        if not late.empty:
            # Later tasks are late because the earlier one is, so name the earliest one only
            first = late.iloc[0]
            reasons.append(f"{len(late)} task(s) past plan, starting with {stage_name(first['stage']).lower()} "
                           f"({int(first['slip_quarters'])} quarter(s))")
        if reasons:
            alerts.append([grant_id, "; ".join(reasons), "review recommended"])
    out += [
        f"{len(alerts)} of {len(running)} running grants.",
        "",
        table(["Grant", "Signal at latest report", "Action"], alerts) if alerts else "",
        "",
        "## limitations",
        "",
        "- All of this is synthetic data. The numbers show that the method runs and how to read it, not "
        "anything about real grants.",
    ]
    tolerance_rows = [s for rule, _, s in experiment[:3]]
    if all(s == tolerance_rows[0] for s in tolerance_rows):
        out.append("- The 0, 5 and 10 point rules give exactly the same result, because the synthetic stalls "
                   "are all complete freezes. There is no slow progress like 40% → 45% to tell them apart, so "
                   "the tolerance itself is untested here.")
    missed_small = main_predictions[main_predictions["grant_id"].isin(main["missed"])]
    if len(missed_small):
        shortest = int(missed_small["planned_months"].min())
        n_short = int((missed_small["planned_months"] == shortest).sum())
        out.append(f"- {n_short} of the {len(main['missed'])} missed extensions are {shortest}-month grants. With "
                   "quarterly reports a short grant only has a few reports before its planned end, and most of "
                   "the missed ones stay close to plan until the last quarter, so there is little to detect early.")
    out += [
        "- A project that stops *before* the next stage has started (still at 0%) is not a stall by this "
        "definition. It shows up in the timetable slip instead, which is why the \"stall or slip\" rule is there.",
        "- The false positive rate of 0 is probably optimistic. The synthetic on-time grants follow their plan "
        "closely, and real projects are noisier.",
        "- There are no extension request dates in the data, so lead time is measured to the planned end, not to "
        "the request.",
        "- Completion is only known to the quarter, so slip is in whole quarters.",
        "- The stage names come from the synthetic forms. The brief lists different ones (pre-data collection, "
        "writing first and final version, review stage, publication stage), so the mapping would need "
        "updating for the real form.",
        "- The `stall_stage` column in the synthetic answer key does not match the reports for 36 of its 84 "
        "grants (they never stop moving), so the detector is checked against the reports instead, see "
        "`tests/test_stall_detector.py`.",
    ]
    return "\n".join(out) + "\n"


def main(argv=None):
    cfg = get_config()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--trajectories", default=cfg.PROCESSED_DIR / "progress_trajectories.csv", type=Path)
    parser.add_argument("--timetables", default=cfg.PROCESSED_DIR / "planned_timetables.csv", type=Path)
    parser.add_argument("--final-reports", default=cfg.PSEUDONYMISED_DIR / "final_reports", type=Path)
    parser.add_argument("--out", default="docs/stall-detection.md", type=Path)
    args = parser.parse_args(argv)

    configure_logging()
    logging.getLogger("app.ingestion.text_extractor").setLevel(logging.WARNING)
    for path, how in [(args.trajectories, "python -m app.progress.progress_trajectories"),
                      (args.timetables, "python inspect_proposals.py"),
                      (args.final_reports, "python -m app.ingestion.pseudonymiser")]:
        if not path.exists():
            logger.error("%s does not exist. Run `%s` first.", path, how)
            return 1

    trajectories = stall_detector.load_trajectories(args.trajectories)
    timetables = timetable_slip.load_timetables(args.timetables)
    outcomes = extension_predictor.read_outcomes(args.final_reports)
    episodes, slip, experiment = build(trajectories, timetables, outcomes, cfg)

    cfg.PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    episodes.to_csv(cfg.PROCESSED_DIR / "stall_episodes.csv", index=False)
    slip.to_csv(cfg.PROCESSED_DIR / "timetable_slip.csv", index=False)
    experiment[0][1].to_csv(cfg.PROCESSED_DIR / "extension_predictions.csv", index=False)
    sources = [shown(args.trajectories), shown(args.timetables), shown(args.final_reports)]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(trajectories, outcomes, episodes, slip, experiment, cfg, sources), encoding="utf-8")
    logger.info("%d stall episodes, %d timetable tasks, %d completed grants; wrote %s",
                len(episodes), len(slip), len(outcomes), args.out)


if __name__ == "__main__":
    sys.exit(main())
