"""Record which review form each review used: all six methodology scores, or C-F combined out of 12.

The brief (section 5.3) says the two forms must not be compared as if they were the same, so every
later analysis needs to know which one a review used. Reads the pseudonymised reviews and writes one
row per review (no reviewer names or codes) plus a short Markdown summary.

    python -m app.ingestion.review_variants [reviews_dir] [--csv ...] [--out docs/review-variants.md]
"""
import argparse
import csv
import logging
import re
import sys
from collections import Counter
from datetime import date
from pathlib import Path

from config.config import ROOT, get_config
from app.ingestion.data_inventory import GRANT_ID, english, fields, parse_form, round_of, table
from app.ingestion.text_extractor import extract_text

logger = logging.getLogger(__name__)

STANDARD, COMBINED, UNKNOWN = "standard", "combined", "unknown"
SEPARATE_CF = {"B3C", "B3D", "B3E", "B3F"}
CODE = re.compile(r"^[A-E]\d[A-F]?$")
ARABIC_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")
COLUMNS = ["review_id", "grant_id", "slot", "variant", "methodology_scores", "criteria_scored",
           "declared_variant", "declared_matches", "score_sum", "stated_total", "total_matches"]


def number(text):
    try:
        return float(text.translate(ARABIC_DIGITS).replace("%", "").strip())
    except (ValueError, AttributeError):
        return None


def declared(text):
    """What the 'Form variant' field on the form says, if anything."""
    text = (text or "").lower()
    if "combined" in text or "مجتمعة" in text:
        return COMBINED
    if "standard" in text or "15" in text:
        return STANDARD
    return UNKNOWN


def read_review(path):
    """One summary row for a review form."""
    _, rows = parse_form(extract_text(path))
    scores = {cells[0].strip(): number(cells[3]) for cells in rows
              if len(cells) >= 4 and CODE.match(cells[0].strip())}
    total = next((number(cells[3]) for cells in rows
                  if len(cells) >= 4 and not cells[0].strip() and english(cells[1]) == "Total"), None)

    codes = set(scores)
    if SEPARATE_CF <= codes:
        variant = STANDARD
    elif "B3" in codes:
        variant = COMBINED
    else:
        variant = UNKNOWN
    said = declared(fields(rows).get("Form variant"))
    score_sum = sum(v for v in scores.values() if v is not None)
    review_id = path.stem.removesuffix("_review")
    grant = GRANT_ID.search(path.name)
    return {
        "review_id": review_id,
        "grant_id": grant.group(0) if grant else "",
        "slot": review_id[-1] if review_id[-2:-1] == "-" else "",
        "variant": variant,
        "methodology_scores": sum(1 for c in codes if c.startswith("B")),
        "criteria_scored": sum(1 for v in scores.values() if v is not None),
        "declared_variant": said,
        "declared_matches": int(said in (variant, UNKNOWN)),
        "score_sum": score_sum,
        "stated_total": total,
        "total_matches": int(total is not None and abs(score_sum - total) < 1e-9),
    }


def scan(reviews_dir):
    records = []
    for path in sorted(Path(reviews_dir).glob("*.docx")):
        if path.name.startswith("~$"):
            continue
        try:
            records.append(read_review(path))
        except Exception as exc:  # corrupt or not really .docx: report it, keep going
            logger.warning("Could not read %s: %s", path.name, exc)
    return records


def shown(path):
    """Path relative to the repo when it is inside it, so the report is the same on every machine."""
    try:
        return Path(path).resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return Path(path).as_posix()


def render(records, reviews_dir):
    by_grant = {}
    for r in records:
        by_grant.setdefault(r["grant_id"], []).append(r["variant"])
    pairs = [v for v in by_grant.values() if len(v) == 2]
    counts = Counter(r["variant"] for r in records)
    rounds = sorted({round_of(r["grant_id"]) for r in records if r["grant_id"]})
    out = [
        "# review form variants",
        "",
        f"Generated by `python -m app.ingestion.review_variants` on {date.today()} from "
        f"`{shown(reviews_dir)}`. One row per review is in `review_variants.csv` next to the",
        "other processed data (not committed).",
        "",
        "- **standard**: methodology scored as six separate criteria (B1, B2, B3C, B3D, B3E, B3F), 15 criteria in all.",
        "- **combined**: criteria C to F given as one mark out of 12 (B1, B2, B3), 12 criteria in all.",
        "",
        "## counts",
        "",
        table(["Round", "Reviews", "Standard", "Combined", "Unknown"],
              [[rnd, sum(1 for r in records if round_of(r["grant_id"]) == rnd)]
               + [sum(1 for r in records if round_of(r["grant_id"]) == rnd and r["variant"] == v)
                  for v in (STANDARD, COMBINED, UNKNOWN)] for rnd in rounds]
              + [["**Total**", f"**{len(records)}**"] + [f"**{counts[v]}**" for v in (STANDARD, COMBINED, UNKNOWN)]]),
        "",
        f"{len(by_grant)} proposals were reviewed: {len(pairs)} by two reviewers and "
        f"{sum(1 for v in by_grant.values() if len(v) == 1)} by one.",
        f"Of the {len(pairs)} pairs, {sum(1 for v in pairs if v[0] == v[1] == STANDARD)} used the standard form twice, "
        f"{sum(1 for v in pairs if v[0] == v[1] == COMBINED)} the combined form twice and "
        f"**{sum(1 for v in pairs if v[0] != v[1])} used one of each**. For those, criteria C to F can only be",
        "compared as a total out of 12 (see docs/statistics-methodology.md).",
        "",
        "## checks",
        "",
        "- Form says a different variant than the scores show: "
        + (", ".join(r["review_id"] for r in records if not r["declared_matches"]) or "none"),
        "- Scores do not add up to the stated total: "
        + (", ".join(r["review_id"] for r in records if not r["total_matches"]) or "none"),
        "- Variant could not be worked out: "
        + (", ".join(r["review_id"] for r in records if r["variant"] == UNKNOWN) or "none"),
    ]
    return "\n".join(out) + "\n"


def main(argv=None):
    cfg = get_config()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("reviews_dir", nargs="?", default=cfg.PSEUDONYMISED_DIR / "reviews", type=Path)
    parser.add_argument("--csv", default=cfg.PROCESSED_DIR / "review_variants.csv", type=Path)
    parser.add_argument("--out", default="docs/review-variants.md", type=Path)
    args = parser.parse_args(argv)

    logging.basicConfig(level=cfg.LOG_LEVEL, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    logging.getLogger("app.ingestion.text_extractor").setLevel(logging.WARNING)
    if not args.reviews_dir.exists():
        logger.error("%s does not exist. Run `python -m app.ingestion.pseudonymiser` first.", args.reviews_dir)
        return 1
    records = scan(args.reviews_dir)
    args.csv.parent.mkdir(parents=True, exist_ok=True)
    with args.csv.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(records)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(records, args.reviews_dir), encoding="utf-8")
    logger.info("Read %d reviews (%s), wrote %s and %s", len(records),
                ", ".join(f"{n} {v}" for v, n in Counter(r["variant"] for r in records).most_common()),
                args.csv, args.out)


if __name__ == "__main__":
    sys.exit(main())
