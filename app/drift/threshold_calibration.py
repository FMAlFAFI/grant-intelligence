"""Experiment 4: calibrate the two drift cut-offs against labelled grant-publication sets.

Procedure fixed in docs/statistics-methodology.md: split the labelled sets in two with the configured
seed, choose on the first half the two cut-offs with the highest Cohen's kappa against the labels,
report kappa on the other half only, then freeze the cut-offs for the whole portfolio.
"""
import argparse
import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd

from app.drift.similarity import ALIGNMENT, LABELS, classify, pair_similarity
from app.ingestion.data_inventory import table
from app.ingestion.language_tagger import tag
from app.logging_setup import configure_logging
from app.statistics.confidence_intervals import rate
from app.statistics.resampling import cohens_kappa, kappa_interval
from config.config import ROOT, get_config

logger = logging.getLogger(__name__)

COMPARISONS = {"abstract": "proposal_abstract", "expected": "expected_outputs"}
THRESHOLDS_FILE = "drift_thresholds.json"


def calibration_mask(n):
    """True for the sets used to choose the cut-offs, False for the sets kept for evaluation."""
    cfg = get_config()
    order = np.random.default_rng(cfg.SEED).permutation(n)
    mask = np.zeros(n, dtype=bool)
    mask[order[:int(round(n * cfg.DRIFT_CALIBRATION_SHARE))]] = True
    return mask


def choose_cutoffs(similarity, labels):
    """The pair of cut-offs with the highest kappa against the labels.

    Candidates are the midpoints between neighbouring similarity values. Ties keep the first pair
    found, scanning from the lowest cut-offs upwards, so the choice is the same on every run.

    Returns:
        (close_cut, distant_cut, kappa)
    """
    values = np.unique(np.asarray(similarity, dtype=float))
    cuts = np.round((values[:-1] + values[1:]) / 2, 4)
    best = None
    for index, distant_cut in enumerate(cuts):
        for close_cut in cuts[index + 1:]:
            kappa = cohens_kappa(labels, classify(similarity, close_cut, distant_cut))
            if not np.isnan(kappa) and (best is None or kappa > best[2] + 1e-12):
                best = (float(close_cut), float(distant_cut), float(kappa))
    if best is None:
        raise ValueError("Cut-offs cannot be calibrated: the labelled sets need at least three similarity values.")
    return best


def calibrate(similarity, labels, in_calibration):
    """Choose the cut-offs on the calibration half and score them on the held-out half.

    Returns:
        dict with the cut-offs, kappa on both halves, the held-out interval, accuracy and the
        predicted label of every set
    """
    similarity, labels = np.asarray(similarity, dtype=float), np.asarray(labels)
    scored = ~np.isnan(similarity)
    fit, held = scored & in_calibration, scored & ~in_calibration
    close_cut, distant_cut, fit_kappa = choose_cutoffs(similarity[fit], labels[fit])
    predicted = classify(similarity, close_cut, distant_cut)
    low, high = kappa_interval(labels[held], predicted[held])
    return {
        "close_cut": close_cut, "distant_cut": distant_cut,
        "calibration_sets": int(fit.sum()), "calibration_kappa": round(fit_kappa, 4),
        "held_out_sets": int(held.sum()), "held_out_kappa": round(cohens_kappa(labels[held], predicted[held]), 4),
        "held_out_kappa_ci": [round(low, 4), round(high, 4)],
        "held_out_correct": int((labels[held] == predicted[held]).sum()),
        "predicted": predicted, "held_out": held,
    }


def confusion(labels, predicted):
    return [[label] + [int(np.sum((labels == label) & (predicted == other))) for other in LABELS] for label in LABELS]


def render(frame, results, source, model, second_rater):
    cfg = get_config()
    level = f"{cfg.CONFIDENCE_LEVEL:.0%}"
    out = [
        "# drift threshold calibration (experiment 4)",
        "",
        f"Generated by `python -m app.drift.threshold_calibration` from `{source}` with `{model}`.",
        "",
        f"{len(frame)} labelled grant–publication sets: "
        + ", ".join(f"{int((frame['researcher_label'] == label).sum())} {label.replace('_', ' ')}" for label in LABELS)
        + f". {int(frame['cross_lingual'].sum())} compare an Arabic proposal with an English publication.",
        "",
        "**What the labels are.** The sets are synthetic scenarios and the labels were written by the analyst who",
        "built them (`reference_label_type` in the file). They stand in for a researcher's labels and were fixed",
        "before any similarity was computed. They are not independent human ratings.",
        (f"A second rater labelled {second_rater['sets']} sets; agreement with the first is kappa "
         f"{second_rater['kappa']:.2f}, which is the ceiling for the figures below."
         if second_rater else
         "There is no second labeller, so the inter-rater ceiling cannot be reported. "
         "`evaluation/drift/researcher_review_template_50.csv` is the blank form for that second rating."),
        "",
        "## procedure",
        "",
        f"0. The sets are split with seed {cfg.SEED}: {int(frame['calibration'].sum())} to choose the cut-offs and "
        f"{int((~frame['calibration']).sum())} held out.",
        "1. On the first half, every pair of cut-offs between neighbouring similarity values is tried and the pair",
        "   with the highest Cohen's kappa against the labels is kept.",
        "2. Kappa is reported on the held-out half only. The cut-offs are then frozen for the whole portfolio.",
        "",
        "## cut-offs and agreement with the labels",
        "",
        table(["Comparison", "Close at or above", "Distant below", "Sets with both texts",
               "Kappa, calibration half", f"Kappa, held-out half ({level} CI)", "Held-out sets labelled the same"],
              [[name, f"{r['close_cut']:.4f}", f"{r['distant_cut']:.4f}", r["calibration_sets"] + r["held_out_sets"],
                f"{r['calibration_kappa']:.2f}",
                f"{r['held_out_kappa']:.2f} ({r['held_out_kappa_ci'][0]:.2f} to {r['held_out_kappa_ci'][1]:.2f})",
                rate(r["held_out_correct"], r["held_out_sets"], cfg.CONFIDENCE_LEVEL)]
               for name, r in results.items()]),
        "",
        "Abstract: the proposal abstract against the publication title. Expected: the proposal's expected",
        "publications against the publication title, for sets where the proposal states them.",
    ]
    for name, result in results.items():
        held = result["held_out"]
        labels, predicted = frame["researcher_label"].to_numpy()[held], result["predicted"][held]
        cross = frame["cross_lingual"].to_numpy()[held]
        out += [
            "",
            f"## held-out confusion, {name} comparison",
            "",
            "Rows are the labels, columns what the cut-offs say.",
            "",
            table(["Label"] + [label.replace("_", " ") for label in LABELS], confusion(labels, predicted)),
            "",
            f"Arabic proposal with English publication: "
            f"{rate(int((labels[cross] == predicted[cross]).sum()), int(cross.sum()), cfg.CONFIDENCE_LEVEL)} labelled "
            f"the same. Same language: "
            f"{rate(int((labels[~cross] == predicted[~cross]).sum()), int((~cross).sum()), cfg.CONFIDENCE_LEVEL)}.",
        ]
    pairing = frame.assign(pairing=np.where(frame["cross_lingual"], "Arabic proposal, English publication",
                                            "same language"))
    summary = pairing.groupby(["pairing", "researcher_label"])["similarity_abstract"].agg(["count", "mean", "min", "max"])
    out += [
        "",
        "## similarity by label and language pairing",
        "",
        "Abstract comparison, all labelled sets. This is why one pair of cut-offs agrees only weakly with the",
        "labels: at the same label, a cross-lingual set scores lower than a same-language set.",
        "",
        table(["Language pairing", "Label", "Sets", "Mean similarity", "Lowest", "Highest"],
              [[index[0], index[1].replace("_", " "), int(row["count"]), f"{row['mean']:.2f}", f"{row['min']:.2f}",
                f"{row['max']:.2f}"] for index, row in summary.iterrows()]),
        "",
        "## limitations",
        "",
        "- The held-out half is small, so the intervals are wide. Read the kappa with its interval.",
        "- Sets from the same grant are not independent; the interval treats them as if they were.",
        "- None of the Arabic-proposal sets is labelled divergent, so the distant cut-off is set by English pairs",
        "  only. Cross-lingual similarity runs lower than same-language similarity, which pushes an aligned",
        "  Arabic proposal into the partial class. Portfolio results are therefore always shown by language",
        "  pairing. Separate cut-offs per pairing need labelled divergent sets with an Arabic proposal first.",
        "- Drift is a distance, not a judgement. A project that found something other than what it set out to",
        "  study may have done excellent work. The Research Unit interprets the distance.",
    ]
    return "\n".join(out) + "\n"


def load_thresholds(path=None):
    """The frozen cut-offs. Stops when they have not been calibrated yet: there is no default value."""
    path = Path(path or get_config().EVALUATION_DIR / "results" / THRESHOLDS_FILE)
    if not path.exists():
        raise FileNotFoundError(
            f"Drift cut-offs not found at {path}. Calibrate them first: python -m app.drift.threshold_calibration")
    return json.loads(path.read_text(encoding="utf-8"))


def main(argv=None):
    cfg = get_config()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("labelled", nargs="?", type=Path,
                        default=cfg.EVALUATION_DIR / "drift" / "synthetic_drift_calibration_50.csv")
    parser.add_argument("--out", default=cfg.EVALUATION_DIR / "results", type=Path)
    parser.add_argument("--report", default=ROOT / "docs" / "drift-calibration.md", type=Path)
    args = parser.parse_args(argv)
    configure_logging()

    from app.classification.embedding_classifier import LockedEncoder

    frame = pd.read_csv(args.labelled, encoding="utf-8-sig")
    required = {"grant_id", "publication_id", "publication_title", "researcher_label", *COMPARISONS.values()}
    missing = required - set(frame.columns)
    if missing:
        raise ValueError(f"{args.labelled.name} is missing columns: {sorted(missing)}")
    unknown = set(frame["researcher_label"]) - set(LABELS)
    if unknown:
        raise ValueError(f"Unknown labels in {args.labelled.name}: {sorted(map(str, unknown))}")

    encoder = LockedEncoder()
    frame["calibration"] = calibration_mask(len(frame))
    frame["cross_lingual"] = [tag(a) != tag(b) for a, b in zip(frame["proposal_abstract"], frame["publication_title"])]
    results = {}
    for name, column in COMPARISONS.items():
        frame[f"similarity_{name}"] = np.round(pair_similarity(encoder, frame[column], frame["publication_title"]), 4)
        results[name] = calibrate(frame[f"similarity_{name}"], frame["researcher_label"], frame["calibration"].to_numpy())
        frame[f"predicted_{name}"] = results[name]["predicted"]

    second = frame.dropna(subset=["second_rater_label"]) if "second_rater_label" in frame else frame.iloc[0:0]
    second_rater = ({"sets": len(second), "kappa": cohens_kappa(second["researcher_label"], second["second_rater_label"])}
                    if len(second) else None)

    args.out.mkdir(parents=True, exist_ok=True)
    model = f"{encoder.model_name}@{encoder.revision[:12]}"
    frozen = {"model": model, "labelled_sets": args.labelled.name, "seed": cfg.SEED,
              "labels": dict(ALIGNMENT), "second_rater_sets": len(second),
              **{name: {key: value for key, value in result.items() if key not in ("predicted", "held_out")}
                 for name, result in results.items()}}
    (args.out / THRESHOLDS_FILE).write_text(json.dumps(frozen, indent=2) + "\n", encoding="utf-8")
    columns = ["grant_id", "publication_id", "calibration", "cross_lingual", "researcher_label",
               "similarity_abstract", "predicted_abstract", "similarity_expected", "predicted_expected"]
    frame[columns].to_csv(args.out / "drift_calibration.csv", index=False, encoding="utf-8-sig")
    source = args.labelled.resolve().relative_to(ROOT).as_posix() if ROOT in args.labelled.resolve().parents else args.labelled.name
    args.report.write_text(render(frame, results, source, model, second_rater), encoding="utf-8")
    for name, result in results.items():
        logger.info("%s: close >= %.4f, distant < %.4f, held-out kappa %.2f on %d sets", name, result["close_cut"],
                    result["distant_cut"], result["held_out_kappa"], result["held_out_sets"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
